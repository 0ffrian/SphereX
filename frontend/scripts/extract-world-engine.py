#!/usr/bin/env python3
"""Extract the approved prototype's world engine (D-37) verbatim into frontend/src/engine/worlds/.

Usage: python3 extract-world-engine.py [SRC_HTML] [OUT_DIR]
The source is sculptor-preview-next.html (sculptor-reference worktree). Every slice is a 1-based
inclusive line range copied byte for byte. The only edits are the named substitutions in SUBS
(references to prototype globals/DOM, plus four timing knobs). Re-run to regenerate; do not hand-edit the output.
"""
import sys, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else '/home/moon/Desktop/Projects/SphereX/.claude/worktrees/sculptor-reference/sculptor-preview-next.html'
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '..', 'src', 'engine', 'worlds')
L = open(SRC, encoding='utf-8').read().split('\n')
SRC_NAME = 'sculptor-preview-next.html'


def sl(a, b, subs=()):
    """Lines a..b (1-based, inclusive) between parity markers (CONTRACT.md A). subs = (old, new) pairs without
    whitespace, declared on a // @rename line; the checker applies exactly those."""
    t = '\n'.join(L[a - 1:b])
    ren = ''
    if subs:
        for old, new in subs:
            assert not re.search(r'\s', old + new), 'rename tokens may not contain whitespace'
            if old not in t:
                raise SystemExit('substitution target not found in %d-%d: %r' % (a, b, old[:60]))
        for old, new in subs:
            t = t.replace(old, new)
        ren = '// @rename ' + ' '.join(o + '=>' + n for o, n in subs) + '\n'
    return '// @verbatim L%d-L%d\n' % (a, b) + ren + t + '\n// @end-verbatim'


def hdr(title, ranges):
    return ('// @ts-nocheck\n// GENERATED by frontend/scripts/extract-world-engine.py from %s (D-37). Do not edit by hand.\n'
            '// %s\n// Verbatim source lines: %s\n' % (SRC_NAME, title, ranges))


HELPERS_IMPORT = "import { clamp, lerp, sstep, fmt, rng, g, planck, planckRGB, LMIN, LMAX, LUT, compile, unis, FULL } from './helpers.js';\n"
HELPERS_NAMES = 'clamp, lerp, sstep, fmt, rng, g, planck, planckRGB, LMIN, LMAX, LUT, compile, unis, FULL'


def w(name, text):
    with open(os.path.join(OUT, name), 'w', encoding='utf-8') as f:
        f.write(text)


os.makedirs(OUT, exist_ok=True)

# helpers.js: clamp lerp sstep fmt rng g planck planckRGB LMIN/LMAX/LUT compile unis FULL (not $, reduced, pills)
w('helpers.js', hdr('helpers: maths, Planck colour, LUT, GL compile', '1267-1270, 1272-1282, 1291-1297') +
  sl(1267, 1270) + '\n' + sl(1272, 1282) + '\n' + sl(1291, 1297) + '\nexport { ' + HELPERS_NAMES + ' };\n')

# shaders.js
w('shaders.js', hdr('shaders: NOISE, ADV_FS, GAS_FS, WORLD_FS, FLY_FS', '1298-1639') +
  "import { LMIN, LMAX } from './helpers.js';\n" + sl(1298, 1639) + '\nexport { NOISE, ADV_FS, GAS_FS, WORLD_FS, FLY_FS };\n')

# presets.js: FLUIDS, WP
w('presets.js', hdr('FLUIDS and WP (example presets)', '1640-1661') + sl(1640, 1661) + '\nexport { FLUIDS, WP };\n')

# terrain.js: CPU noise, buildTerrain, routeTerrain (pure)
w('terrain.js', hdr('CPU value noise, plate-tectonic terrain build, river routing', '1728-1860') + HELPERS_IMPORT +
  sl(1727, 1860) + '\nexport { hsh, vn3, fbm3, buildTerrain, routeTerrain };\n')

# gas.js: GAS_NODES, gasProfile, GasSim (pure)
w('gas.js', hdr('gas giants: GAS_NODES, gasProfile, GasSim', '2010-2122') + HELPERS_IMPORT +
  sl(2009, 2122) + '\nexport { GAS_NODES, gasProfile, GasSim };\n')

# core.js: stateful pieces, closed over one instance state (W, EB, GS, OCEANF, ORB)
core = []
core.append(hdr('stateful engine core: one closure per WorldEngine instance',
                '1662-1664, 1666-1726, 1861-1913(+1914-2008), 2123-2246, 2248, 2250-2270, 2274-2285, 2289, 2291-2303, 2305-2306, 2311, 2328-2330, 2332-2346'))
core.append("""import { FULL, compile, unis, LUT, clamp, lerp, sstep, fmt, rng, planck, planckRGB } from './helpers.js';
import { ADV_FS, GAS_FS, WORLD_FS, FLY_FS } from './shaders.js';
import { FLUIDS, WP } from './presets.js';
import { fbm3, buildTerrain, routeTerrain } from './terrain.js';
import { GAS_NODES, gasProfile, GasSim } from './gas.js';

/** Build one engine instance on a canvas. */
export function createCore(canvas) {
var reduced = false;
""")
core.append(sl(1662, 1726))                 # ORB, applySpin, W, slider constants, psatFn, worldModel
core.append(sl(1861, 2008))                 # hydroRaster, EB
core.append(sl(2123, 2216, [('(ema', '(!window.__sxPin&&ema')]))       # WorldGL
core.append(sl(2217, 2246))                 # fly camera, flyMove, globePick, GS
core.append(sl(2248, 2248))                 # km
# worldUi: rows and caption captured as data instead of written into the DOM
core.append('function worldUi() {')
core.append(sl(2250, 2270))
core.append("  W.rows = rows; W.mixed = mixed;")
core.append(sl(2274, 2285, [("$('#world-cap').textContent", "W.cap")]))
core.append(sl(2289, 2289, [("$('#world-tag').textContent", "W.tag")]))
core.append('}')
core.append(sl(2291, 2303))                 # resetWorld (its worldUi() call stays)
core.append('function setPreset(p) {')
core.append(sl(2305, 2306))
core.append(sl(2311, 2311))
core.append('}')
core.append("W.timeSec = 300; W.simAcc = 0;")
core.append(sl(2328, 2330))                 # altRange altToS sToAlt
core.append(sl(2332, 2346))                 # flyAimPeak, flyAimDefault
core.append("""
W.gl = new WorldGL(canvas);
return {
  W: W, EB: EB, ORB: ORB, OCEANF: OCEANF, GAS_NODES: GAS_NODES, FLUIDS: FLUIDS,
  getGS: function () { return GS; },
  worldModel: worldModel, worldUi: worldUi, resetWorld: resetWorld, setPreset: setPreset, applySpin: applySpin,
  flyMove: flyMove, globePick: globePick, flyCamera: flyCamera, groundKm: groundKm,
  flyAimPeak: flyAimPeak, flyAimDefault: flyAimDefault, altRange: altRange, altToS: altToS, sToAlt: sToAlt,
};
}
""")
text = '\n'.join(core)
w('core.js', text)
print('wrote', OUT)
