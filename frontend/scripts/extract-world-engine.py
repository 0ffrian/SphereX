#!/usr/bin/env python3
"""Extract the approved prototype's world engine (D-37) verbatim into frontend/src/engine/worlds/.

Usage: python3 extract-world-engine.py SRC_HTML [OUT_DIR] [--force]
       (or set SX_PREVIEW_HTML instead of passing SRC_HTML)
The source is sculptor-preview-next.html (sculptor-reference worktree). Every slice is a 1-based
inclusive line range copied byte for byte. The only edits are the named substitutions in SUBS
(references to prototype globals/DOM, plus four timing knobs).

PR #89 review: the committed engine files now carry reviewed physics fixes, marked `// @deviation`
(with `@rename` pairs or split `@verbatim` blocks) that this script does not reproduce. It refuses to
overwrite a file holding a `@deviation` unless --force is given; port those deviations into SUBS (or
into the prototype) before regenerating, or the fixes are lost.

Issue #93 (phase 1, the first-open freeze and performance): its deviations ARE ported here (the DEV93_* texts, the
split WorldGL slices and their SUBS), with the PR #89 renames of the same slices (shaders.js, WorldGL). Still not
ported from PR #89: the L1701-L1726 and L1728-L1765 renames with the L1727 split, the gas.js renames, and core.js's
header lines 4-5.
"""
import sys, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
FORCE = '--force' in sys.argv
ARGS = [a for a in sys.argv[1:] if a != '--force']
SRC = ARGS[0] if ARGS else os.environ.get('SX_PREVIEW_HTML')
if not SRC:
    raise SystemExit('usage: extract-world-engine.py SRC_HTML [OUT_DIR] [--force] (or set SX_PREVIEW_HTML)')
OUT = ARGS[1] if len(ARGS) > 1 else os.path.join(HERE, '..', 'src', 'engine', 'worlds')
L = open(SRC, encoding='utf-8').read().split('\n')
SRC_NAME = 'sculptor-preview-next.html'


def sl(a, b, subs=()):
    """Lines a..b (1-based, inclusive) between parity markers (CONTRACT.md A). subs = (old, new) pairs without
    whitespace, declared on a // @rename line; the checker applies exactly those."""
    t = '\n'.join(L[a - 1:b])
    ren = ''
    if subs:
        for old, new in subs:
            assert not re.search(r'\s', old + new), 'rename tokens may not contain whitespace'
            if old not in t:
                raise SystemExit('substitution target not found in %d-%d: %r' % (a, b, old[:60]))
        for old, new in subs:
            t = t.replace(old, new)
        ren = '// @rename ' + ' '.join(o + '=>' + n for o, n in subs) + '\n'
    return '// @verbatim L%d-L%d\n' % (a, b) + ren + t + '\n// @end-verbatim'


def hdr(title, ranges):
    return ('// @ts-nocheck\n// GENERATED by frontend/scripts/extract-world-engine.py from %s (D-37). Do not edit by hand.\n'
            '// %s\n// Verbatim source lines: %s\n' % (SRC_NAME, title, ranges))


HELPERS_IMPORT = "import { clamp, lerp, sstep, fmt, rng, g, planck, planckRGB, LMIN, LMAX, LUT, compile, unis, FULL } from './helpers.js';\n"
HELPERS_NAMES = 'clamp, lerp, sstep, fmt, rng, g, planck, planckRGB, LMIN, LMAX, LUT, compile, unis, FULL'


def w(name, text):
    path = os.path.join(OUT, name)
    if not FORCE and os.path.exists(path):
        with open(path, encoding='utf-8') as f:
            if '@deviation' in f.read():
                raise SystemExit('%s holds reviewed @deviation fixes (PR #89) that this script would drop; '
                                 'port them into SUBS first, or pass --force' % path)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(text)


