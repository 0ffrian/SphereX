_NAMES = {n.lower() for n in (*ABBREVIATIONS, *GENITIVES)} | {"boötis"}
_FLAMSTEED = re.compile(r"^\d{1,3}\s+(.+?)(?:\s+[A-Za-z]{1,2})?$")


def is_flamsteed(name: str) -> bool:
    """``<number> <constellation>`` with an optional component letter (``61 Cyg A``)."""
    text = re.sub(r"\s+", " ", name.strip())
    m = re.match(r"^\d{1,3}\s+(.+)$", text)
    if not m:
        return False
    rest = m.group(1).lower()
    if rest in _NAMES:
        return True
    m2 = _FLAMSTEED.match(text)
    return bool(m2 and m2.group(1).lower() in _NAMES)
