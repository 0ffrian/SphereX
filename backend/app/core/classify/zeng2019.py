# Tabulated temperature (K) -> 100% H2O curve; the rule picks the one nearest to pl_eqt.
WATER_CURVES: dict[float, tuple[tuple[float, float], ...]] = {
    300.0: PURE_WATER_300K,
    500.0: PURE_WATER_500K,
    700.0: PURE_WATER_700K,
    1000.0: PURE_WATER_1000K,
}


def water_curve_for(eqt_k: float | None) -> tuple[float, tuple[tuple[float, float], ...]] | None:
    """The tabulated water curve nearest to ``eqt_k`` (ties go to the colder one); None when
    pl_eqt is missing or above the hottest table (1000 K): no water model applies."""
    if eqt_k is None or not math.isfinite(eqt_k) or eqt_k > max(WATER_CURVES):
        return None
    t = min(sorted(WATER_CURVES), key=lambda k: abs(k - eqt_k))
    return t, WATER_CURVES[t]


def radius_on_curve(curve: tuple[tuple[float, float], ...], mass_earth: float) -> float | None:
    """Radius (Earth radii) on ``curve`` at ``mass_earth``; None outside the table's range."""
    if not (mass_earth > 0) or not math.isfinite(mass_earth):
        return None
    if mass_earth < curve[0][0] or mass_earth > curve[-1][0]:
        return None
    masses = [m for m, _ in curve]
    i = bisect_left(masses, mass_earth)
    if masses[i] == mass_earth:
        return curve[i][1]
    (m0, r0), (m1, r1) = curve[i - 1], curve[i]
    return r0 + (r1 - r0) * (math.log(mass_earth) - math.log(m0)) / (math.log(m1) - math.log(m0))
